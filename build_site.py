"""Build the static site Render serves from site/.

    python3 build_site.py

Render cannot rebuild the explorer: it comes from data/observations.json, which
stays out of git because raw feed URLs can carry victim personal data. So the
site is built here, checked, and committed.
"""
import base64
import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).parent
SITE = ROOT / "site"
ARTIFACT = "https://claude.ai/artifact/DSYSNZVtP5zUZxhGwrS4zo"
# the query API's own example URLs are the only query strings allowed on the site
API_HOST = "barnabas-team.us.ainiro.io/magic/modules/campaign-graph/"


def run(*cmd: str) -> None:
    subprocess.run(cmd, cwd=ROOT, check=True)


def main() -> None:
    (SITE / "reports").mkdir(parents=True, exist_ok=True)
    run(sys.executable, "-m", "cgraph", "ui", "--truth", "truth.tags.csv",
        "--out", "site/index.html", "--link", "CG-0001 report=reports/cg0001.html",
        "--link", "API=api.html")
    run(sys.executable, "investigations/render.py", "docs/API.md", "site/api.html",
        "--home=index.html", "--untagged")

    # The report README links the claude.ai copies; on this site they point home.
    md = (ROOT / "investigations/CG-0001/README.md").read_text()
    md = re.sub(r"^Rendered page: .*\n\n", "", md, flags=re.M)
    md = md.replace(ARTIFACT, "../index.html")
    tmp = SITE / "reports" / "cg0001.md"
    tmp.write_text(md)
    run(sys.executable, "investigations/render.py", str(tmp), "site/reports/cg0001.html",
        "--home=../index.html")
    tmp.unlink()

    # Refuse to publish anything that looks like victim data or a live query string.
    bad = []
    for f in SITE.rglob("*.html"):
        s = f.read_text()
        # defanged examples in the report ("trckthepage[.]com/…?click_id=") are fine
        live = [u for u in re.findall(r"https?://([^\"'\s<]*)\?", s)
                if "[.]" not in u and "&lt;" not in u and not u.startswith(API_HOST)]
        if live:
            bad.append(f"{f}: URL with a query string: {live[0][:60]}")
        # a real tracker value is long; the report's truncated "var9=44…" is not
        if re.search(r"var(?:[4-9]|10)=[^&\"\s<…]{5,}|%40", s):
            bad.append(f"{f}: tracker field value")
        if "claude.ai/artifact" in s:
            bad.append(f"{f}: claude.ai link left in")
    if bad:
        sys.exit("refusing to build:\n  " + "\n  ".join(bad))
    write_render_yaml()
    print("site/ ready:", ", ".join(str(p.relative_to(SITE)) for p in sorted(SITE.rglob("*.html"))))


def write_render_yaml() -> None:
    """Pin every inline <script> by hash, so injected script cannot run.

    Inline style attributes stay allowed: the explorer writes colour dots with
    style="", and the pages make no network requests at all (connect-src 'none').
    """
    hashes = set()
    for f in SITE.rglob("*.html"):
        for body in re.findall(r"<script>(.*?)</script>", f.read_text(), flags=re.S):
            digest = hashlib.sha256(body.encode()).digest()
            hashes.add("'sha256-" + base64.b64encode(digest).decode() + "'")
    csp = ("default-src 'none'; script-src " + " ".join(sorted(hashes) or ["'none'"]) +
           "; style-src 'unsafe-inline'; font-src 'self'; img-src data:; connect-src 'none'; base-uri 'none'; "
           "form-action 'none'; frame-ancestors 'none'")
    headers = {
        "Content-Security-Policy": csp,
        "X-Content-Type-Options": "nosniff",
        "Referrer-Policy": "no-referrer",
        "Permissions-Policy": "camera=(), microphone=(), geolocation=()",
        "Strict-Transport-Security": "max-age=31536000",
    }
    lines = ["# Generated by build_site.py: run it again after changing the site.",
             "services:", "  - type: web", "    name: campaign-graph", "    runtime: static",
             '    buildCommand: echo "site/ is prebuilt by build_site.py"',
             "    staticPublishPath: ./site", "    headers:"]
    for name, value in headers.items():
        lines += ["      - path: /*", f"        name: {name}", f'        value: "{value}"']
    (ROOT / "render.yaml").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
